#!/usr/bin/env python3
"""Generate recording wrappers from Vulkan declarations; pointer parameters require an explicit snapshot rule."""
import argparse
from pathlib import Path
import re

ARRAY_COUNTS = {
    'pDescriptorSets': 'descriptorSetCount', 'pDynamicOffsets': 'dynamicOffsetCount',
    'pBuffers': 'bindingCount', 'pOffsets': 'bindingCount', 'pViewports': 'viewportCount',
    'pScissors': 'scissorCount', 'pAttachments': 'attachmentCount', 'pRects': 'rectCount',
    'pRegions': 'regionCount', 'pRanges': 'rangeCount', 'pValues': 'size',
    'pMemoryBarriers': 'memoryBarrierCount', 'pBufferMemoryBarriers': 'bufferMemoryBarrierCount',
    'pImageMemoryBarriers': 'imageMemoryBarrierCount',
    'pColor': '1', 'pDepthStencil': '1',
}
STRUCTS = {'VkRenderingInfo': 'rendering', 'VkDependencyInfo': 'dependency',
           'VkRenderPassBeginInfo': 'renderpass'}
PNEXT_ARRAYS = {'VkMemoryBarrier', 'VkBufferMemoryBarrier', 'VkImageMemoryBarrier'}
# Only value-only elements may use the generic array rule. A future *Copy2 or extension
# structure needs its own pNext/nested-pointer handling even when its parameter is named pRegions.
PLAIN_ARRAYS = {
    'VkDescriptorSet', 'VkDeviceSize', 'VkBuffer', 'VkViewport', 'VkRect2D',
    'VkClearAttachment', 'VkClearRect', 'VkImageBlit', 'VkClearColorValue',
    'VkClearDepthStencilValue', 'VkImageSubresourceRange', 'VkBufferCopy',
    'VkBufferImageCopy', 'VkImageCopy', 'VkImageResolve', 'float', 'uint32_t', 'void',
} | PNEXT_ARRAYS
PROTECT = {
    'vkCreateCommandPool', 'vkAllocateCommandBuffers', 'vkFreeCommandBuffers', 'vkDestroyCommandPool',
    'vkResetCommandPool', 'vkBeginCommandBuffer', 'vkEndCommandBuffer', 'vkResetCommandBuffer',
    'vkQueueSubmit', 'vkQueueSubmit2', 'vkQueueSubmit2KHR', 'vkQueueWaitIdle', 'vkDeviceWaitIdle',
    'vkResetDescriptorPool', 'vkDestroyDescriptorPool', 'vkDestroyBuffer', 'vkDestroyImage',
    'vkDestroyImageView', 'vkDestroySampler', 'vkDestroyPipeline', 'vkDestroyPipelineLayout',
    'vkDestroyRenderPass', 'vkDestroyFramebuffer', 'vkFreeMemory',
    'vkDestroyQueryPool', 'vkFreeDescriptorSets', 'vkDestroyDescriptorSetLayout',
}


def declaration(header, name):
    match = re.search(r'typedef\s+(\w+)\s+\(VKAPI_PTR\s*\*PFN_' + name + r'\)\s*\((.*?)\);', header, re.S)
    if not match:
        alias = re.search(r'typedef\s+PFN_(\w+)\s+PFN_' + name + r'\s*;', header)
        if alias:
            return declaration(header, alias[1])
        raise ValueError('No Vulkan declaration: ' + name)
    params = []
    for raw in match[2].split(','):
        raw = ' '.join(raw.split())
        if raw == 'void':
            continue
        m = re.fullmatch(r'(.+?)([a-zA-Z_]\w*)\s*(?:\[(\d+)\])?', raw)
        if not m:
            raise ValueError('Unsupported parameter: ' + raw)
        typ, arg, fixed = m.groups()
        typ = typ.strip()
        if fixed:
            typ += '*'
        params.append((typ, arg, fixed))
    return match[1], params


def generate(root, header, out):
    texts = [p.read_text() for p in (root / 'runtime/nvn/vulkan').iterdir()
             if p.suffix in ('.c', '.cpp', '.h') and p.name not in ('command_worker.c', 'command_worker.h')]
    commands = sorted(set(re.findall(r'\bvkCmd\w+', '\n'.join(texts))))
    decl, code = ['// Generated by tools/gen_vk_command_worker.py; do not edit.\n#pragma once'], []
    prototypes, macros = [], []
    for op, name in enumerate(commands, 1):
        result, params = declaration(header, name)
        if result != 'void':
            raise ValueError('Recording command must return void: ' + name)
        signature = ', '.join(t + ' ' + a for t, a, _ in params)
        args = ', '.join(a for _, a, _ in params)
        prototypes.append(f'CW_HIDDEN VKAPI_ATTR void VKAPI_CALL cw_{name}({signature});')
        macros.append(f'#define {name}(...) cw_{name}(__VA_ARGS__)')
        typ = 'CW_' + name
        fields = '; '.join(t + ' ' + a for t, a, _ in params) + ';'
        code.append(f'typedef struct {{ CWHeader header; {fields} }} {typ};')
        rules = []
        for t, a, fixed in params:
            if '*' not in t:
                continue
            base = t.replace('const', '').replace('*', '').strip()
            if base in STRUCTS:
                rules.append((a, STRUCTS[base], None, base))
            else:
                count = fixed or ARRAY_COUNTS.get(a)
                if count is None or base not in PLAIN_ARRAYS:
                    raise ValueError(f'No snapshot rule for {name}: {t} {a}')
                rules.append((a, 'array', count, 'uint8_t' if base == 'void' else base))
        code.append(f'static void run_{name}(void *data) {{ {typ} p; memcpy(&p, data, sizeof p);')
        for a, rule, _, base in rules:
            code.append(f'    p.{a} = cw_pointer(data, p.{a});')
            if rule != 'array':
                code.append(f'    cw_fix_{rule}((void *)p.{a}, data);')
        code.append(f'    {name}(' + ', '.join('p.' + a for _, a, _ in params) + ');\n}')
        code.append(f'VKAPI_ATTR void VKAPI_CALL cw_{name}({signature}) {{')
        code.append(f'    if (!cw_owned()) {{ {name}({args}); return; }}')
        code.append(f'    size_t cw_size_ = sizeof({typ});')
        checks = []
        for a, rule, count, base in rules:
            if rule == 'array':
                checks.append(f'cw_array_size(&cw_size_, {a}, (size_t)({count}), sizeof({base}))')
                if base in PNEXT_ARRAYS:
                    checks.append(f'cw_plain_{base}({a}, (size_t)({count}))')
            else:
                checks.append(f'cw_size_{rule}(&cw_size_, {a})')
        condition = ' || '.join('!' + c for c in checks) or 'false'
        code.append(f'    void *data = NULL;\n    if ({condition} || !(data = cw_reserve(cw_size_))) {{')
        code.append(f'        cw_fallback(); {name}({args}); return;\n    }}')
        init = ', '.join('.' + a + ' = ' + a for _, a, _ in params)
        code.append(f'    {typ} p = {{.header = {{{op}, (uint32_t)cw_align(cw_size_), 0}}, {init}}};')
        if rules:
            code.append('    size_t cursor = sizeof p;')
        for a, rule, count, base in rules:
            if rule == 'array':
                code.append(f'    p.{a} = cw_copy(data, &cursor, {a}, (size_t)({count}) * sizeof({base}));')
            else:
                code.append(f'    p.{a} = cw_copy_{rule}(data, &cursor, {a});')
        code.append('    memcpy(data, &p, sizeof p); cw_finish(cw_align(cw_size_));\n}')
    code.append('static void cw_execute(void *data) {\n    CWHeader *h = data;\n    switch (h->op) {')
    for op, name in enumerate(commands, 1):
        code.append(f'    case {op}: run_{name}(data); break;')
    code.append('    default: abort();\n    }\n}')
    for name in sorted(PROTECT):
        result, params = declaration(header, name)
        signature = ', '.join(t + ' ' + a for t, a, _ in params)
        args = ', '.join(a for _, a, _ in params)
        prototypes.append(f'CW_HIDDEN VKAPI_ATTR {result} VKAPI_CALL cw_{name}({signature});')
        macros.append(f'#define {name}(...) cw_{name}(__VA_ARGS__)')
        ret = 'return ' if result != 'void' else ''
        code.append(f'VKAPI_ATTR {result} VKAPI_CALL cw_{name}({signature}) {{')
        code.append(f'    if (cw_owned()) vk_command_worker_flush();\n    {ret}{name}({args});\n}}')
    decl += prototypes + ['#ifndef VK_COMMAND_WORKER_IMPLEMENTATION'] + macros + ['#endif\n']
    out.mkdir(parents=True, exist_ok=True)
    for name, body in [('vk_command_worker_decl.h', '\n'.join(decl)),
                       ('vk_command_worker_packets.inc', '\n'.join(code))]:
        path = out / name
        if not path.exists() or path.read_text() != body:
            path.write_text(body)
    print(f'Generated {len(commands)} recording commands and {len(PROTECT)} synchronization boundaries')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--header', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    args = p.parse_args()
    generate(Path(__file__).resolve().parents[1], args.header.read_text(), args.out)
